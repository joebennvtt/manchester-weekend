// Merges data/*.json (excluding sample.json) into data/places.js. `--sample` uses sample.json only.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { validateFiles } from './validate.mjs';

const dataDir = join(dirname(fileURLToPath(import.meta.url)), '..', 'data');
const useSample = process.argv.includes('--sample');
const files = useSample
  ? ['sample.json']
  : readdirSync(dataDir).filter((f) => f.endsWith('.json') && f !== 'sample.json').sort();

const { errorCount } = validateFiles(files.map((f) => join(dataDir, f)));
if (errorCount > 0) {
  console.error(`Refusing to write data/places.js: ${errorCount} validation error(s)`);
  process.exit(1);
}

const places = files.flatMap((f) => {
  const arr = JSON.parse(readFileSync(join(dataDir, f), 'utf8'));
  if (!Array.isArray(arr)) throw new Error(`${f} is not a JSON array`);
  return arr;
});
const header = `// GENERATED by scripts/build-data.mjs${useSample ? ' --sample' : ''}. Do not edit by hand.\n`;
writeFileSync(join(dataDir, 'places.js'), `${header}window.PLACES = ${JSON.stringify(places, null, 2)};\n`);
console.log(`Wrote data/places.js with ${places.length} places from ${files.join(', ')}`);
